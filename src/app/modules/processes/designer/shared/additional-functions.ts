/*
 * The additional functions of a device command task: controlling functions sent in the same message as the primary
 * one, each with its own value. They live in the payload input parameter of the task, next to the primary function.
 */

import {
    DeviceTypeAspectNodeModel,
    DeviceTypeCharacteristicsModel,
    DeviceTypeFunctionModel,
} from '../../../metadata/device-types-overview/shared/device-type.model';
import { selectedAspectNodes } from '../bpmn-js/properties-provider/aspects';

/** Payload key of the additional functions; written only when there are some. */
export const additionalFunctionsKey = 'additional_functions';

/** Prefix of the task input parameters of an additional function; the function's name follows the colon. */
export const additionalInputPrefix = 'inputs:';

/** An additional function as the payload holds it. The characteristic is not in the payload; a dialog loads it from the function's concept. */
export interface StoredAdditionalFunctionModel {
    name: string;
    function: DeviceTypeFunctionModel;
    characteristic_id: string;
    aspects: DeviceTypeAspectNodeModel[];
}

/** An additional function as a dialog hands it to the writers. */
export interface AdditionalFunctionModel extends StoredAdditionalFunctionModel {
    characteristic: DeviceTypeCharacteristicsModel;
}

export type AdditionalFunctionNameError = 'empty' | 'characters' | 'duplicate';

/**
 * The rules the engine enforces at deploy: the name is not empty, has no '.' and no ':', and is unique within the task.
 * Blanks around the name do not count, as the writers store the trimmed name.
 */
export function additionalFunctionNameError(name: string, otherNames: string[]): AdditionalFunctionNameError | null {
    const trimmed = name.trim();
    if (trimmed === '') {
        return 'empty';
    }
    if (trimmed.includes('.') || trimmed.includes(':')) {
        return 'characters';
    }
    if (otherNames.some((other) => other.trim() === trimmed)) {
        return 'duplicate';
    }
    return null;
}

/** The entries of a parsed payload; an entry without a name or a function is left out. */
export function parseAdditionalFunctions(payload: unknown): StoredAdditionalFunctionModel[] {
    const raw = isRecord(payload) ? payload[additionalFunctionsKey] : undefined;
    const entries: unknown[] = Array.isArray(raw) ? raw : [];
    return entries.flatMap((entry) => {
        if (!isRecord(entry) || typeof entry['name'] !== 'string' || !isRecord(entry['function'])) {
            return [];
        }
        const aspects: unknown = entry['aspects'];
        return [{
            name: entry['name'],
            function: entry['function'] as DeviceTypeFunctionModel,
            characteristic_id: typeof entry['characteristic_id'] === 'string' ? entry['characteristic_id'] : '',
            aspects: selectedAspectNodes({ aspects: Array.isArray(aspects) ? aspects : [] }),
        }];
    });
}

function isRecord(value: unknown): value is Record<string, unknown> {
    return value !== null && typeof value === 'object';
}

/**
 * The entries as the payload holds them. The input is the default structure of the characteristic, generated by the
 * caller the way it generates the input of the primary function.
 */
export function serializeAdditionalFunctions(
    entries: AdditionalFunctionModel[],
    defaultInput: (characteristic: DeviceTypeCharacteristicsModel) => unknown,
): object[] {
    return entries.map((entry) => ({
        name: entry.name.trim(),
        function: entry.function,
        characteristic_id: entry.characteristic.id,
        aspects: selectedAspectNodes({ aspects: entry.aspects }),
        input: defaultInput(entry.characteristic),
    }));
}

/**
 * The additional functions of the task with the given id in a BPMN XML string. Undefined when the element has no
 * payload, so a caller can fall back to another version of the diagram; an empty list when the payload has none.
 */
export function additionalFunctionsOfElement(xml: string, elementId: string): StoredAdditionalFunctionModel[] | undefined {
    if (!xml) {
        return undefined;
    }
    const doc = new DOMParser().parseFromString(xml, 'text/xml');
    const element = Array.from(doc.getElementsByTagName('*')).find((candidate) => candidate.getAttribute('id') === elementId);
    const text = element ? payloadText(element) : undefined;
    if (text === undefined) {
        return undefined;
    }
    try {
        return parseAdditionalFunctions(JSON.parse(text));
    } catch {
        return undefined;
    }
}

/** The text of the payload input parameter in the first extension element, where the writers put it. */
function payloadText(element: Element): string | undefined {
    const extensions = childrenNamed(element, 'extensionElements')[0];
    const inputOutput = extensions ? Array.from(extensions.children)[0] : undefined;
    if (!inputOutput) {
        return undefined;
    }
    const payload = childrenNamed(inputOutput, 'inputParameter').find((input) => input.getAttribute('name') === 'payload');
    return payload ? payload.textContent ?? '' : undefined;
}

function childrenNamed(parent: Element, localName: string): Element[] {
    return Array.from(parent.children).filter((child) => child.localName === localName);
}
